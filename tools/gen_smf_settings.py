"""Generates src/SMFSettings.inc, the settings table for the SKSE Menu Framework pages, from the MCM Helper
config that ships with the mod (MCM/Config/DebugMenu/config.json + the english translation file), so both
menus list the same settings with the same text, ranges and defaults.

usage: python tools/gen_smf_settings.py "<mod folder with MCM/ and Interface/>"
"""
import json, re, sys, pathlib

BS = chr(92)  # backslash

mod = pathlib.Path(sys.argv[1])
repo = pathlib.Path(__file__).resolve().parent.parent

cfg = json.loads((mod / "MCM/Config/DebugMenu/config.json").read_text(encoding="utf-8-sig"), strict=False)

tr = {}
for line in (mod / "Interface/Translations/DebugMenu_english.txt").read_text(encoding="utf-16").splitlines():
    if line.startswith("$") and "\t" in line:
        k, v = line.split("\t", 1)
        tr[k.strip()] = v.strip()

# the translation file has a few typos that would show up in the new menu
FIXES = {"Info: scroll on hotkey": "Info: scroll down hotkey", "Eanble Free Cam": "Enable Free Cam",
         "Civli War": "Civil War"}

def text(s):
    s = tr.get(s, s)
    for a, b in FIXES.items():
        s = s.replace(a, b)
    return s

# (section, key) -> (kind, MCM::settings member), taken from the code that reads the ini
src = (repo / "src/MCM.cpp").read_text(encoding="utf-8-sig")
vars_ = {}
for m in re.finditer(r'Read(Bool|Float|UInt32)Setting\(ini,\s*"(\w+)",\s*"(\w+)",\s*settings::(\w+)\)', src):
    vars_[(m.group(2), m.group(3))] = (m.group(1), m.group(4))

def cstr(s):
    return '"' + s.replace(BS, BS + BS).replace('"', BS + '"').replace("\n", " ").replace("\t", " ") + '"'

def fmt(f, is_int):
    f = (f or "{0}").replace("%", "%%")
    return re.sub(r"\{(\d)\}", lambda m: "%d" if is_int else "%." + m.group(1) + "f", f)

pages = []
out = ["// generated by tools/gen_smf_settings.py from the MCM config, do not edit by hand", ""]
missing = []
for pi, page in enumerate(cfg["pages"]):
    pages.append(text(page["pageDisplayName"]))
    for e in page["content"]:
        t = e.get("type")
        if t == "header":
            out.append(f"SMF_HEADER({pi}, {cstr(text(e['text']))})")
            continue
        if "id" not in e:
            continue
        key, section = e["id"].split(":")
        if (section, key) not in vars_:
            missing.append(e["id"])
            continue
        kind, member = vars_[(section, key)]
        label, help_ = text(e["text"]), text(e.get("help", ""))
        vo = e.get("valueOptions", {})
        common = f"{pi}, {cstr(section)}, {cstr(key)}, &MCM::settings::{member}, {cstr(label)}, {cstr(help_)}"
        if t == "toggle":
            assert kind == "Bool", e["id"]
            out.append(f"SMF_BOOL({common})")
        elif t == "keymap":
            assert kind == "UInt32", e["id"]
            out.append(f"SMF_KEY({common})")
        elif t == "color":
            assert kind == "UInt32", e["id"]
            out.append(f"SMF_COLOR({common})")
        elif t == "enum":
            assert kind == "UInt32", e["id"]
            opts = "".join(text(o) + BS + "0" for o in vo["options"])
            out.append(f'SMF_ENUM({common}, "{opts}")')
        elif t == "slider":
            lo, hi = vo.get("min", 0), vo.get("max", 100)
            if kind == "Float":
                out.append(f"SMF_FLOAT({common}, {float(lo)}f, {float(hi)}f, {cstr(fmt(vo.get('formatString'), False))})")
            else:
                out.append(f"SMF_UINT({common}, {int(lo)}, {int(hi)}, {cstr(fmt(vo.get('formatString'), True))})")
        else:
            raise SystemExit("unhandled type " + str(t) + " " + e["id"])

out.append("")
out.append("// page names, in order")
out.append("#define SMF_PAGE_NAMES " + ", ".join(cstr(p) for p in pages))
(repo / "src/SMFSettings.inc").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print("pages:", pages)
print("entries:", sum(1 for l in out if l.startswith("SMF_") and not l.startswith("SMF_HEADER")), "missing:", missing)
